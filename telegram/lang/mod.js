const esc = (t) => String(t ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function tr(ctx) {
    const lang = langOf(ctx.userId, (ctx.message || ctx.callbackQuery)?.from?.language_code);
    const fn = (key, vars = {}) => {
        let v = (T[lang] && T[lang][key] !== undefined) ? T[lang][key] : T.en[key];
        if (typeof v !== 'string') return v;
        for (const [k, x] of Object.entries(vars)) { const raw = k.endsWith("_html"); v = v.split(`{${raw ? k.slice(0, -5) : k}}`).join(raw ? String(x) : esc(x)); }
        return v;
    };
    return fn;
}
module.exports = { tr, _T: T };
