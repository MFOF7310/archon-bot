// tools/sync-emojis.js
// Usage: DISCORD_TOKEN=... node tools/sync-emojis.js
// Régénère config/emojis.js depuis les Application Emojis Discord

const fs = require('fs');
const path = require('path');

const APP_ID = process.env.DISCORD_APP_ID || process.env.CLIENT_ID || process.env.APPLICATION_ID;
const REGISTRY_PATH = path.join(__dirname, '..', 'config', 'emojis.js');
const TOKEN = process.env.DISCORD_TOKEN;

if (!TOKEN) { console.error('❌ DISCORD_TOKEN manquant'); process.exit(1); }

(async () => {
    console.log('🔄 Fetch app emojis...');
    const res = await fetch(`https://discord.com/api/v10/applications/${APP_ID}/emojis`, {
        headers: { Authorization: `Bot ${TOKEN}` }
    });
    if (!res.ok) { console.error(`❌ API ${res.status}: ${await res.text()}`); process.exit(1); }
    const { items } = await res.json();
    console.log(`✅ ${items.length} app emojis récupérés`);

    // Charge l'ancien registry pour garder les clés custom
    delete require.cache[require.resolve(REGISTRY_PATH)];
    const old = require(REGISTRY_PATH);

    // Map nom app → {id, animated}
    const appByName = new Map();
    for (const e of items) appByName.set(e.name.toLowerCase(), { id: e.id, animated: !!e.animated });

    // Pour chaque clé du registry, retrouve l'emoji par NOM (pas par ID)
    const lines = [];
    let remapped = 0, missing = 0, unchanged = 0;

    for (const [key, val] of Object.entries(old)) {
        const m = String(val || '').match(/<a?:(\w+):(\d+)>/);
        if (!m) { lines.push(`    ${key}: ${JSON.stringify(val)},`); continue; }
        const [, name, oldId] = m;
        const app = appByName.get(name.toLowerCase());
        if (!app) {
            lines.push(`    ${key}: ${JSON.stringify(val)},   // ⚠️ introuvable côté app`);
            missing++;
            continue;
        }
        if (app.id === oldId) { unchanged++; }
        else { remapped++; }
        const prefix = app.animated ? 'a' : '';
        lines.push(`    ${key}: '<${prefix}:${name}:${app.id}>',`);
    }

    const header = `/**
 * ARCHON CG-223 — Application Emoji Registry
 *
 * AUTO-GENERATED by tools/sync-emojis.js — do not edit manually
 * Last sync: ${new Date().toISOString()}
 * Source: Discord Application ${APP_ID} (app emojis)
 *
 * Régénérer: DISCORD_TOKEN=... node tools/sync-emojis.js
 */

module.exports = {
${lines.join('\n')}
};
`;

    fs.writeFileSync(REGISTRY_PATH, header);
    console.log(`\n📊 Résultat:`);
    console.log(`  🔧 Remappés  : ${remapped}`);
    console.log(`  ✅ Inchangés : ${unchanged}`);
    console.log(`  ❌ Manquants : ${missing}`);
    console.log(`\n✅ Écrit dans ${REGISTRY_PATH}`);
})().catch(e => { console.error(e); process.exit(1); });
